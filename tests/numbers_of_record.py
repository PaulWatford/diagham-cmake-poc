#!/usr/bin/env python3
"""Write the page of figures of record: every number the README, the documentation and the reports quote.

Usage: tests/numbers_of_record.py <build-dir> [--write docs/reference/numbers.md] [--check]

Reads `ctest --show-only=json-v1` from the build directory (through tests/coverage.py, whose counting it
reuses), the open-findings register, scripts_cmake/upstream-revision.txt and the project version in
CMakeLists.txt. Each row of the page names what produced it. The page carries no date, so --check is a plain
comparison: it regenerates the page and compares it with the committed file from line 5 on (the lines above
name the build and the commit), exiting 1 with the first row that differs.
"""
import argparse, re, subprocess, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import coverage  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
LABEL_ORDER = ("physics", "crosscheck", "regression", "smoke", "selftest", "open-finding", "python", "install")
PAGE = "docs/reference/numbers.md"
CHECK_FROM_LINE = 5


def project_version():
    """The version as scripts_cmake/check_version.py reads it: project(DiagHam VERSION x.y.z)."""
    m = re.search(r"project\(DiagHam\s+VERSION\s+([0-9.]+)", (ROOT / "CMakeLists.txt").read_text())
    return m.group(1) if m else "not read"


def render(build_dir, programs_dir):
    import os
    build_abs = os.path.abspath(build_dir)
    tests = coverage.ctest_json(build_dir)["tests"]
    sm = coverage.summary(tests, build_abs, programs_dir)

    def labels_of(t):
        for prop in t.get("properties", []):
            if prop["name"] == "LABELS":
                return set(prop["value"])
        return set()
    by_label = {}
    for t in tests:
        for l in labels_of(t):
            by_label[l] = by_label.get(l, 0) + 1
    register = (ROOT / "docs/reference/open-findings.md").read_text(encoding="utf-8")
    n_register = sum(1 for l in register.splitlines() if re.match(r"^\| U\d+ \|", l))
    n_of_tests = by_label.get("open-finding", 0)
    revision = (ROOT / "scripts_cmake/upstream-revision.txt").read_text().strip()
    try:
        commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True,
                                text=True).stdout.strip() or "not read"
    except OSError:
        commit = "not read"
    preset = Path(build_abs).name

    json_src = "`ctest --show-only=json-v1`"
    cov_src = "`tests/coverage.py` (`summary`), from " + json_src
    rows = [("tests registered", len(tests), json_src + ": the tests of this build")]
    for l in LABEL_ORDER:
        rows.append((f"tests labelled `{l}`", by_label.get(l, 0), json_src + ": `LABELS`"))
    for l in sorted(set(by_label) - set(LABEL_ORDER)):
        rows.append((f"tests labelled `{l}`", by_label[l], json_src + ": `LABELS`"))
    rows += [
        ("programs in the build", sm["programs"], cov_src + " and the program reference"),
        ("programs with a `physics` test", sm["physics"], cov_src),
        ("programs with a `crosscheck` test", sm["crosscheck"], cov_src),
        ("programs with a `physics` or `crosscheck` test", sm["physics_or_crosscheck"], cov_src),
        ("programs with a `regression` test", sm["regression"], cov_src),
        ("programs with a `physics`, `crosscheck` or `regression` test", sm["any"], cov_src),
        ("programs with only a `smoke` test", sm["smoke_only"], cov_src),
        ("programs with no test at all", sm["none"], cov_src),
        ("open findings registered", n_register, "rows `| Uxx |` of `docs/reference/open-findings.md`"),
        ("tests labelled `open-finding` (reproducers)", n_of_tests, json_src + ": `LABELS`"),
        ("upstream revision carried", revision, "`scripts_cmake/upstream-revision.txt`"),
        ("project version", project_version(), "`project(DiagHam VERSION ...)` in `CMakeLists.txt`, as "
                                               "`scripts_cmake/check_version.py` reads it"),
        ("physics tests with a `KNOWN_FROM` source", "not available: KNOWN_FROM not yet registered", "(phase 2)"),
    ]
    lines = [
        "<!-- generated by tests/numbers_of_record.py; do not edit -->",
        "# Numbers of record",
        "",
        f"Source: the `{preset}` build at commit `{commit}`. Regenerate with "
        f"`python3 tests/numbers_of_record.py <build-dir> --write {PAGE}`; `scripts_cmake/ci.sh default` fails when it is stale.",
        "Purpose: every figure the README, the documentation and the project reports quote, from one build; "
        "each row names what produced it.",
        "",
        "| Figure | Value | Produced by |",
        "|---|---|---|",
    ]
    lines += [f"| {f} | {v} | {src} |" for f, v, src in rows]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("build_dir")
    ap.add_argument("--write", help="write the page here")
    ap.add_argument("--check", action="store_true", help=f"compare with the committed {PAGE}; exit 1 if stale")
    ap.add_argument("--programs-dir", default=str(ROOT / "docs/reference/programs"))
    a = ap.parse_args()
    page = render(a.build_dir, a.programs_dir)
    if a.write:
        Path(a.write).write_text(page, encoding="utf-8")
    if a.check:
        committed = (ROOT / PAGE).read_text(encoding="utf-8").splitlines()[CHECK_FROM_LINE - 1:]
        fresh = page.splitlines()[CHECK_FROM_LINE - 1:]
        for i, (x, y) in enumerate(zip(committed, fresh)):
            if x != y:
                print(f"{PAGE} is stale at line {i + CHECK_FROM_LINE}: committed {x!r}, this build {y!r}; "
                      f"regenerate with python3 tests/numbers_of_record.py <build-dir> --write {PAGE}", file=sys.stderr)
                return 1
        if len(committed) != len(fresh):
            print(f"{PAGE} is stale: {len(committed)} lines from line {CHECK_FROM_LINE}, this build gives {len(fresh)}",
                  file=sys.stderr)
            return 1
        print(f"{PAGE} is current")
    if not a.write and not a.check:
        sys.stdout.write(page)
    return 0


if __name__ == "__main__":
    sys.exit(main())
