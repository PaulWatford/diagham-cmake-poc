#!/usr/bin/env python3
"""Independent exact diagonalisation for FTIGenericInteractionFromFileTwoBands (numpy, nothing shared with DiagHam).

    python3 tests/oracles/fti_generic.py --write tests/data/fti_generic
    python3 tests/oracles/fti_generic.py --check tests/data/fti_generic    (selftest.fti_generic_oracle, needs numpy)
    python3 tests/oracles/fti_generic.py run PROGRAM CASE CONVENTION DATA_DIR WORK_DIR TOLERANCE   (the tests)

The program diagonalises spinless fermions in two bands on an Nx x Ny momentum grid, with one-body energies and a
two-body interaction both read from text files (the formats of its wiki page, no spin and no valley):
  one-body file:  kx ky m E(k, m)                              (2 Nx Ny lines, --singleparticle-file)
  interaction:    m1 kx1 ky1 m2 kx2 ky2 m3 kx3 ky3 m4 kx4 ky4 V   (--interaction-file, --real-interaction)
Here both are generated by closed formulas: generic one-body energies (no degeneracy), and a real interaction that
conserves momentum (k1 + k2 = k3 + k4 mod the grid) and is symmetric under exchanging both pairs (1 2 | 3 4 ->
2 1 | 4 3) and under hermiticity (1 2 | 3 4 -> 3 4 | 1 2). Every such element is listed. The oracle builds
H = sum_{k,m} E(k,m) n_{k,m} + sum V(1,2,3,4) c+_1 c+_2 c_3 c_4 on the explicit Fock basis of each total-momentum
sector, with fermion signs from the sorted mode order, and diagonalises it densely. The operator order of that
term (c_3 c_4, not c_4 c_3) is the one convention taken from the program, fixed on two particles; the
three-particle spectra are then a check with nothing left to adjust.

Two conventions of the program (U48):
- with --3band-convention ("the safest option", its help says) the band index m means the same band in both files;
- without it (the default), the m of the interaction file acts on the opposite band from the m of the one-body
  file: the default Hilbert space applies the two-body operators to bit 2k + 1 - m and the one-body operator to bit
  2k + m. The "default" spectra below are built with that swap, so a change of the default is noticed.
Each case writes the two input files and "<case>_<convention>_spectrum.dat", every eigenvalue as "kx ky E" lines.
"""
import argparse, itertools, math, sys
from pathlib import Path



def onebody(nx, ny):
    return {(kx, ky, m): 0.8 * math.cos(2 * math.pi * kx / nx + 0.3) - 0.45 * math.sin(2 * math.pi * ky / ny + 0.1)
            + (1.7 + 0.13 * kx - 0.07 * ky) * m + 0.011 * (kx * ny + ky) for kx in range(nx) for ky in range(ny) for m in (0, 1)}


def _g(a, b, c, d):
    """A real function of four modes with no symmetry of its own."""
    (m1, x1, y1), (m2, x2, y2), (m3, x3, y3), (m4, x4, y4) = a, b, c, d
    return (math.cos(0.7 * x1 - 0.4 * x3 + 0.9 * y2 + 0.2 * m1 + 0.31 * m4) * (0.5 + 0.1 * (m2 + m3))
            + 0.3 * math.sin(1.1 * y1 + 0.6 * x4 - 0.5 * x2 + 0.17 * m3) / (1 + 0.2 * (x1 + y3)))


def interaction(nx, ny):
    """Every momentum-conserving element, symmetrised: V(1,2,3,4) = V(2,1,4,3) = V(3,4,1,2)."""
    modes = [(m, kx, ky) for kx in range(nx) for ky in range(ny) for m in (0, 1)]
    v = {}
    for a, b, c in itertools.product(modes, repeat=3):
        dx, dy = (a[1] + b[1] - c[1]) % nx, (a[2] + b[2] - c[2]) % ny
        for m4 in (0, 1):
            d = (m4, dx, dy)
            val = (_g(a, b, c, d) + _g(b, a, d, c) + _g(c, d, a, b) + _g(d, c, b, a)) / 4
            v[(a, b, c, d)] = val
    return v


def spectrum(nx, ny, n, convention):
    """Every eigenvalue, sector by sector: {(Kx, Ky): sorted list}. convention: "3band" or "default" (U48)."""
    import numpy as np
    eps = onebody(nx, ny)
    v = interaction(nx, ny)
    if convention == "default":       # the interaction's band labels act on the opposite bands
        v = {tuple((1 - x[0],) + x[1:] for x in key): val for key, val in v.items()}
    modes = [(m, kx, ky) for kx in range(nx) for ky in range(ny) for m in (0, 1)]
    index = {mode: i for i, mode in enumerate(modes)}
    out = {}
    for KX in range(nx):
        for KY in range(ny):
            states = [s for s in itertools.combinations(range(len(modes)), n)
                      if sum(modes[i][1] for i in s) % nx == KX and sum(modes[i][2] for i in s) % ny == KY]
            if not states:
                continue
            pos = {s: i for i, s in enumerate(states)}
            H = np.zeros((len(states), len(states)))
            for s in states:
                i = pos[s]
                H[i, i] += sum(eps[(modes[j][1], modes[j][2], modes[j][0])] for j in s)
                occ = list(s)
                for (a, b, c, d), val in v.items():           # c+_a c+_b c_c c_d, c_d acts first
                    ia, ib, ic, id_ = index[a], index[b], index[c], index[d]
                    if ic not in occ or id_ not in occ or ic == id_:
                        continue
                    l = list(occ)
                    sign = (-1) ** l.index(id_)
                    l.remove(id_)
                    sign *= (-1) ** l.index(ic)
                    l.remove(ic)
                    if ib in l:
                        continue
                    l = sorted(l + [ib])
                    sign *= (-1) ** l.index(ib)
                    if ia in l:
                        continue
                    l = sorted(l + [ia])
                    sign *= (-1) ** l.index(ia)
                    H[pos[tuple(l)], i] += sign * val
            out[(KX, KY)] = sorted(np.linalg.eigvalsh(H))
    return out


CASES = {  # name -> (Nx, Ny, N)
    "fermions_x3_y2_n2": (3, 2, 2),
    "fermions_x3_y2_n3": (3, 2, 3),
    "fermions_x2_y2_n3": (2, 2, 3),
}
CONVENTIONS = {"fermions_x3_y2_n2": ("3band", "default"), "fermions_x3_y2_n3": ("3band",), "fermions_x2_y2_n3": ("3band",)}


def render(name):
    nx, ny, n = CASES[name]
    eps = onebody(nx, ny)
    v = interaction(nx, ny)
    head = f"# {name}: generated by tests/oracles/fti_generic.py, do not edit\n"
    ob = head + "".join(f"{kx} {ky} {m} {eps[(kx, ky, m)]!r}\n" for kx in range(nx) for ky in range(ny) for m in (0, 1))
    it = head + "".join(f"{a[0]} {a[1]} {a[2]} {b[0]} {b[1]} {b[2]} {c[0]} {c[1]} {c[2]} {d[0]} {d[1]} {d[2]} {val!r}\n"
                        for (a, b, c, d), val in sorted(v.items()))
    out = {f"x{nx}_y{ny}_onebody.dat": ob, f"x{nx}_y{ny}_interaction.dat": it}
    for conv in CONVENTIONS[name]:
        sp = spectrum(nx, ny, n, conv)
        out[f"{name}_{conv}_spectrum.dat"] = head + f"# convention {conv}\n# kx ky E\n" + "".join(
            f"{kx} {ky} {e:.17g}\n" for (kx, ky), es in sorted(sp.items()) for e in es)
    return out


def run(argv):
    """Run the program on a case and compare every momentum sector with the stored spectrum."""
    import os, subprocess, glob
    prog, name, conv, data, work, tol = argv
    prog, data, work = (os.path.abspath(x) for x in (prog, data, work))
    rel = float(tol.split(":", 1)[1]) if tol.startswith("rel:") else float(tol)
    nx, ny, n = CASES[name]
    os.makedirs(work, exist_ok=True)
    for f in glob.glob(os.path.join(work, "*")):
        os.remove(f)
    cmd = [prog, "-x", str(nx), "-y", str(ny), "-p", str(n), "--interaction-file", os.path.join(data, f"x{nx}_y{ny}_interaction.dat"),
           "--interaction-name", "oracle", "--real-interaction", "--singleparticle-file", os.path.join(data, f"x{nx}_y{ny}_onebody.dat"),
           "--full-diag", "5000"] + (["--3band-convention"] if conv == "3band" else [])
    r = subprocess.run(cmd, cwd=work, capture_output=True, text=True, timeout=600)
    outs = [f for f in glob.glob(os.path.join(work, "fermions_twoband_*.dat")) if "tightbinding" not in f]
    if r.returncode != 0 or len(outs) != 1:
        print(r.stdout[-1500:], r.stderr[-1500:]); print(f"program exit {r.returncode}, outputs {outs}"); return 1

    def sectors(path):
        d = {}
        for l in open(path):
            if l.strip() and not l.startswith("#"):
                w = l.split()
                d.setdefault((int(w[0]), int(w[1])), []).append(float(w[-1]))
        return {k: sorted(v) for k, v in d.items()}
    got, want = sectors(outs[0]), sectors(os.path.join(data, f"{name}_{conv}_spectrum.dat"))
    problems, worst = [], 0.0
    if sorted(got) != sorted(want):
        problems.append(f"sectors {sorted(got)}, expected {sorted(want)}")
    for k in want:
        g, w = got.get(k, []), want[k]
        if len(g) != len(w):
            problems.append(f"sector {k}: {len(g)} levels, expected {len(w)}")
            continue
        for x, y in zip(g, w):
            dev = abs(x - y) / max(abs(x), abs(y), 1.0)
            worst = max(worst, dev)
        if max(abs(x - y) / max(abs(x), abs(y), 1.0) for x, y in zip(g, w)) > rel:
            problems.append(f"sector {k}: largest relative deviation above {rel:g}")
    print(f"{name} ({conv} convention): {sum(len(v) for v in got.values())} levels in {len(got)} sectors, "
          f"largest relative deviation {worst:.1e} (allowed {rel:g})")
    for p_ in problems:
        print("  " + p_)
    return 1 if problems else 0


def main():
    if len(sys.argv) > 2 and sys.argv[1] == "run":
        sys.exit(run(sys.argv[2:]))
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", metavar="DIR")
    ap.add_argument("--check", metavar="DIR")
    a = ap.parse_args()
    files = {}
    for name in CASES:
        files.update(render(name))
    if a.write:
        d = Path(a.write)
        d.mkdir(parents=True, exist_ok=True)
        for f, text in files.items():
            (d / f).write_text(text)
        print(f"wrote {len(files)} files to {d}")
    if a.check:
        d = Path(a.check)
        bad = 0
        for f, text in files.items():
            stored = (d / f).read_text()
            if not f.endswith("_spectrum.dat"):
                if stored != text:
                    print(f"{f} differs from the oracle's"); bad += 1
                continue
            rows = lambda t: [tuple(map(float, l.split())) for l in t.splitlines() if l and not l.startswith("#")]
            x, y = rows(stored), rows(text)
            if len(x) != len(y) or max(abs(p[2] - q[2]) for p, q in zip(x, y)) > 1e-12 or any(p[:2] != q[:2] for p, q in zip(x, y)):
                print(f"{f}: stored spectrum differs from the oracle's"); bad += 1
        print("fti_generic oracle:", "OK" if not bad else f"{bad} problems")
        sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
