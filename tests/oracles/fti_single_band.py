#!/usr/bin/env python3
"""Independent exact diagonalisation for FTIGenericInteractionFromFileSingleBand (numpy, nothing shared with DiagHam).

    python3 tests/oracles/fti_single_band.py --write tests/data/fti_single_band
    python3 tests/oracles/fti_single_band.py --check tests/data/fti_single_band    (selftest.fti_single_band_oracle, needs numpy)
    python3 tests/oracles/fti_single_band.py run PROGRAM CASE DATA_DIR WORK_DIR TOLERANCE [OPTION...]   (the tests)

The program diagonalises spinless fermions in one band on an Nx x Ny momentum grid, with a complex two-body
interaction read from a text file and optional one-body energies (the formats of its wiki page, no spin, no valley):
  interaction:    kx1 ky1 kx2 ky2 kx3 ky3 kx4 ky4 (Re V,Im V)     (--interaction-file)
  one-body file:  kx ky E(k)                                       (Nx Ny lines, --singleparticle-file)
Here both are generated by closed formulas: generic one-body energies (no degeneracy), and a complex interaction that
conserves momentum (k1 + k2 = k3 + k4 mod the grid), is symmetric under exchanging both pairs (1 2 | 3 4 -> 2 1 | 4 3)
and hermitian (V(3 4 | 1 2) = V(1 2 | 3 4)*). Every such element is listed, as in Nicolas Regnault's 5 x 5 example.
The oracle builds H = sum_k E(k) n_k + sum V(1,2,3,4) c+_1 c+_2 c_3 c_4 on the explicit Fock basis of each
total-momentum sector, with fermion signs from the sorted mode order, and diagonalises it densely. The operator order
(c_3 c_4, not c_4 c_3) is that of FTIGenericInteractionFromFileTwoBands (tests/oracles/fti_generic.py): both programs
build their interaction in ParticleOnLatticeFromFileInteractionTwoBandHamiltonian::EvaluateInteractionFactors. The
two-particle case fixes it (the other order fails there); the three- and four-particle spectra are then a check with
nothing left to adjust. Each case writes its input files and "<case>_spectrum.dat", every eigenvalue as "kx ky E".
"""
import argparse, cmath, itertools, math, sys
from pathlib import Path


def onebody(nx, ny):
    return {(kx, ky): 0.8 * math.cos(2 * math.pi * kx / nx + 0.3) - 0.45 * math.sin(2 * math.pi * ky / ny + 0.1)
            + 0.013 * (kx * ny + ky) for kx in range(nx) for ky in range(ny)}


def _g(a, b, c, d):
    """A complex function of four momenta with no symmetry of its own."""
    (x1, y1), (x2, y2), (x3, y3), (x4, y4) = a, b, c, d
    amp = (math.cos(0.7 * x1 - 0.4 * x3 + 0.9 * y2) * 0.5
           + 0.3 * math.sin(1.1 * y1 + 0.6 * x4 - 0.5 * x2) / (1 + 0.2 * (x1 + y3)))
    return amp * cmath.exp(1j * (0.37 * x1 - 0.81 * y4 + 0.23 * x2 * y3 + 0.5))


def interaction(nx, ny):
    """Every momentum-conserving element: V(1,2,3,4) = V(2,1,4,3) = V(3,4,1,2)*."""
    ks = [(kx, ky) for kx in range(nx) for ky in range(ny)]
    v = {}
    for a, b, c in itertools.product(ks, repeat=3):
        d = ((a[0] + b[0] - c[0]) % nx, (a[1] + b[1] - c[1]) % ny)
        v[(a, b, c, d)] = (_g(a, b, c, d) + _g(b, a, d, c) + _g(c, d, a, b).conjugate() + _g(d, c, b, a).conjugate()) / 4
    return v


def spectrum(nx, ny, n, with_onebody, order="34"):
    """Every eigenvalue, sector by sector: {(Kx, Ky): sorted list}. order "43" is the rejected operator order."""
    import numpy as np
    eps = onebody(nx, ny) if with_onebody else {}
    v = interaction(nx, ny)
    ks = [(kx, ky) for kx in range(nx) for ky in range(ny)]
    index = {k: i for i, k in enumerate(ks)}
    out = {}
    for KX in range(nx):
        for KY in range(ny):
            states = [s for s in itertools.combinations(range(len(ks)), n)
                      if sum(ks[i][0] for i in s) % nx == KX and sum(ks[i][1] for i in s) % ny == KY]
            if not states:
                continue
            pos = {s: i for i, s in enumerate(states)}
            H = np.zeros((len(states), len(states)), dtype=complex)
            for s in states:
                i = pos[s]
                H[i, i] += sum(eps.get(ks[j], 0.0) for j in s)
                for (a, b, c, d), val in v.items():           # c+_a c+_b c_c c_d, c_d acts first ("34")
                    ia, ib, ic, id_ = index[a], index[b], index[c], index[d]
                    if order == "43":
                        ic, id_ = id_, ic
                    if ic not in s or id_ not in s or ic == id_:
                        continue
                    l = list(s)
                    sign = (-1) ** l.index(id_)
                    l.remove(id_)
                    sign *= (-1) ** l.index(ic)
                    l.remove(ic)
                    if ib in l:
                        continue
                    l = sorted(l + [ib])
                    sign *= (-1) ** l.index(ib)
                    if ia in l:
                        continue
                    l = sorted(l + [ia])
                    sign *= (-1) ** l.index(ia)
                    H[pos[tuple(l)], i] += sign * val
            if np.abs(H - H.conj().T).max() > 1e-12:
                raise SystemExit(f"sector {(KX, KY)}: the oracle's Hamiltonian is not hermitian")
            out[(KX, KY)] = sorted(np.linalg.eigvalsh(H))
    return out


CASES = {  # name -> (Nx, Ny, N, with one-body energies)
    "fermions_x3_y2_n2": (3, 2, 2, True),
    "fermions_x3_y3_n3": (3, 3, 3, True),
    "fermions_x4_y3_n4": (4, 3, 4, False),
}


def render(name):
    nx, ny, n, ob = CASES[name]
    v = interaction(nx, ny)
    head = f"# {name}: generated by tests/oracles/fti_single_band.py, do not edit\n"
    out = {f"x{nx}_y{ny}_interaction.dat": head + "# kx_1 ky_1 kx_2 ky_2 kx_3 ky_3 kx_4 ky_4 matrix_element\n" + "".join(
        f"{a[0]} {a[1]} {b[0]} {b[1]} {c[0]} {c[1]} {d[0]} {d[1]} ({val.real!r},{val.imag!r})\n"
        for (a, b, c, d), val in sorted(v.items()))}
    if ob:
        eps = onebody(nx, ny)
        out[f"x{nx}_y{ny}_onebody.dat"] = head + "".join(f"{kx} {ky} {eps[(kx, ky)]!r}\n" for kx in range(nx) for ky in range(ny))
    sp = spectrum(nx, ny, n, ob)
    out[f"{name}_spectrum.dat"] = head + "# kx ky E\n" + "".join(
        f"{kx} {ky} {e:.17g}\n" for (kx, ky), es in sorted(sp.items()) for e in es)
    return out


def sectors(path):
    d = {}
    for line in open(path):
        if line.strip() and not line.startswith("#"):
            w = line.split()
            d.setdefault((int(w[0]), int(w[1])), []).append(float(w[-1]))
    return {k: sorted(v) for k, v in d.items()}


def run(argv):
    """Run the program on a case and compare every momentum sector with the stored spectrum; OPTIONs go to the program."""
    import os, subprocess, glob
    prog, name, data, work, tol, extra = argv[0], argv[1], argv[2], argv[3], argv[4], argv[5:]
    prog, data, work = (os.path.abspath(x) for x in (prog, data, work))
    rel = float(tol.split(":", 1)[1]) if tol.startswith("rel:") else float(tol)
    nx, ny, n, ob = CASES[name]
    os.makedirs(work, exist_ok=True)
    for f in glob.glob(os.path.join(work, "*")):
        os.remove(f)
    cmd = [prog, "-x", str(nx), "-y", str(ny), "-p", str(n), "--interaction-file", os.path.join(data, f"x{nx}_y{ny}_interaction.dat"),
           "--interaction-name", "oracle", "--full-diag", "5000"]
    if ob:
        cmd += ["--singleparticle-file", os.path.join(data, f"x{nx}_y{ny}_onebody.dat")]
    cmd += extra
    r = subprocess.run(cmd, cwd=work, capture_output=True, text=True, timeout=600)
    outs = [f for f in glob.glob(os.path.join(work, "fermions_oneband_*.dat")) if "tightbinding" not in f]
    if r.returncode != 0 or len(outs) != 1:
        print(r.stdout[-1500:], r.stderr[-1500:]); print(f"program exit {r.returncode}, outputs {outs}"); return 1
    got, want = sectors(outs[0]), sectors(os.path.join(data, f"{name}_spectrum.dat"))
    problems, worst = [], 0.0
    if sorted(got) != sorted(want):
        problems.append(f"sectors {sorted(got)}, expected {sorted(want)}")
    for k in want:
        g, w = got.get(k, []), want[k]
        if len(g) != len(w):
            problems.append(f"sector {k}: {len(g)} levels, expected {len(w)}")
            continue
        devs = [abs(x - y) / max(abs(x), abs(y), 1.0) for x, y in zip(g, w)]
        worst = max([worst] + devs)
        if max(devs) > rel:
            problems.append(f"sector {k}: largest relative deviation above {rel:g}")
    print(f"{name}: {sum(len(v) for v in got.values())} levels in {len(got)} sectors, "
          f"largest relative deviation {worst:.1e} (allowed {rel:g})")
    for p_ in problems:
        print("  " + p_)
    return 1 if problems else 0


def main():
    if len(sys.argv) > 2 and sys.argv[1] == "run":
        sys.exit(run(sys.argv[2:]))
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", metavar="DIR")
    ap.add_argument("--check", metavar="DIR")
    ap.add_argument("--order-check", action="store_true",
                    help="show that the two-particle spectra of the two operator orders differ (the case that fixes it)")
    a = ap.parse_args()
    if a.order_check:
        nx, ny, n, ob = CASES["fermions_x3_y2_n2"]
        s34, s43 = spectrum(nx, ny, n, ob, "34"), spectrum(nx, ny, n, ob, "43")
        print("largest difference between the two orders:", max(abs(x - y) for k in s34 for x, y in zip(s34[k], s43[k])))
        return
    files = {}
    for name in CASES:
        files.update(render(name))
    if a.write:
        d = Path(a.write)
        d.mkdir(parents=True, exist_ok=True)
        for f, text in files.items():
            (d / f).write_text(text)
        print(f"wrote {len(files)} files to {d}")
    if a.check:
        d = Path(a.check)
        bad = 0
        for f, text in files.items():
            if not f.endswith("_spectrum.dat"):
                if (d / f).read_text() != text:
                    print(f"{f} differs from the oracle's"); bad += 1
                continue
            x, y = sectors(d / f), {}
            for line in text.splitlines():
                if line and not line.startswith("#"):
                    w = line.split()
                    y.setdefault((int(w[0]), int(w[1])), []).append(float(w[2]))
            if sorted(x) != sorted(y) or any(len(x[k]) != len(y[k]) or max(abs(p - q) for p, q in zip(x[k], sorted(y[k]))) > 1e-12 for k in y):
                print(f"{f}: stored spectrum differs from the oracle's"); bad += 1
        print("fti_single_band oracle:", "OK" if not bad else f"{bad} problems")
        sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
